const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'jev-sync-f2-'));
process.env.HOME = root;
process.env.USERPROFILE = root;
process.env.CLAUDE_CONFIG_DIR = path.join(root, '.claude');
process.env.CODEX_HOME = path.join(root, '.codex');
fs.mkdirSync(process.env.CLAUDE_CONFIG_DIR);
fs.mkdirSync(process.env.CODEX_HOME);
fs.mkdirSync(path.join(root, 'dotfiles'));
fs.writeFileSync(path.join(root, 'dotfiles', 'AGENTS.md'), 'Shared rule: run tests.\n');
fs.writeFileSync(path.join(process.env.CLAUDE_CONFIG_DIR, 'CLAUDE.md'), '# CLAUDE.md\n\n@~/dotfiles/AGENTS.md\n');

const sync = require('../plugin/scripts/jev-sync');

test('sync keeps a shared AGENTS.md import and stays unchanged', (t) => {
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const results = [];
  const sizes = [];
  for (let i = 0; i < 4; i++) {
    results.push(sync.syncAgents({}));
    sizes.push(fs.statSync(sync.agentsPath).size);
  }
  const output = fs.readFileSync(sync.agentsPath, 'utf8');
  assert.match(output, /Shared rule: run tests\./);
  assert.equal((output.match(/Generated by the mynameisjev/g) || []).length, 1);
  assert.deepEqual(results, ['updated', 'unchanged', 'unchanged', 'unchanged']);
  assert.deepEqual(sizes, [sizes[0], sizes[0], sizes[0], sizes[0]]);
});
