const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const SYNC = require.resolve('../plugin/scripts/jev-sync');

function caseInsensitive(dir) {
  fs.writeFileSync(path.join(dir, 'Probe'), '');
  const folded = fs.existsSync(path.join(dir, 'probe'));
  fs.rmSync(path.join(dir, 'Probe'));
  return folded;
}

// jev-sync reads its directories from the environment when it loads.
function setup(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'jev-sync-s1-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  process.env.HOME = root;
  process.env.USERPROFILE = root;
  process.env.CLAUDE_CONFIG_DIR = path.join(root, '.claude');
  process.env.CODEX_HOME = path.join(root, '.codex');
  fs.mkdirSync(process.env.CLAUDE_CONFIG_DIR);
  fs.mkdirSync(process.env.CODEX_HOME);
  fs.mkdirSync(path.join(root, 'dotfiles'));
  fs.writeFileSync(path.join(root, 'dotfiles', 'agents.md'), 'Shared rule: run tests.\n');
  fs.writeFileSync(path.join(process.env.CLAUDE_CONFIG_DIR, 'CLAUDE.md'), '# CLAUDE.md\n\n@~/dotfiles/agents.md\n');
  delete require.cache[SYNC];
  return { root, sync: require(SYNC), folds: caseInsensitive(process.env.CODEX_HOME) };
}

test('sync does not re-include AGENTS.md through a differently cased import name', (t) => {
  const { sync, folds } = setup(t);
  // A case-insensitive volume resolves agents.md to the generated AGENTS.md.
  // On a case-sensitive one a symlink gives the same name-to-file mapping.
  if (!folds) fs.symlinkSync('AGENTS.md', path.join(process.env.CODEX_HOME, 'agents.md'));
  const results = [];
  const sizes = [];
  for (let i = 0; i < 4; i++) {
    results.push(sync.syncAgents({}));
    sizes.push(fs.statSync(sync.agentsPath).size);
  }
  const output = fs.readFileSync(sync.agentsPath, 'utf8');
  assert.match(output, /Shared rule: run tests\./);
  assert.equal((output.match(/Generated by the mynameisjev/g) || []).length, 1);
  assert.deepEqual(results, ['updated', 'unchanged', 'unchanged', 'unchanged']);
  assert.deepEqual(sizes, [sizes[0], sizes[0], sizes[0], sizes[0]]);
});

test('sync still uses a separate Codex file whose name differs from AGENTS.md only by case', (t) => {
  const { sync, folds } = setup(t);
  if (folds) return t.skip('volume is case-insensitive: agents.md and AGENTS.md are one file');
  fs.writeFileSync(path.join(process.env.CODEX_HOME, 'agents.md'), 'Codex variant rule.\n');
  assert.equal(sync.syncAgents({}), 'updated');
  assert.equal(sync.syncAgents({}), 'unchanged');
  const output = fs.readFileSync(sync.agentsPath, 'utf8');
  assert.match(output, /Codex variant rule\./);
  assert.doesNotMatch(output, /Shared rule: run tests\./);
});

function syncFourTimes(sync) {
  const results = [];
  const sizes = [];
  for (let i = 0; i < 4; i++) {
    results.push(sync.syncAgents({}));
    sizes.push(fs.statSync(sync.agentsPath).size);
  }
  return { results, sizes, output: fs.readFileSync(sync.agentsPath, 'utf8') };
}

for (const name of ['AGENTS.md', 'AGENTS.md.jev.bak']) {
  test(`sync does not read ${name} back in when CLAUDE.md imports it directly`, (t) => {
    const { sync } = setup(t);
    fs.writeFileSync(path.join(process.env.CLAUDE_CONFIG_DIR, 'CLAUDE.md'), `# CLAUDE.md\n\nKeep this rule.\n\n@~/.codex/${name}\n`);
    // An earlier generated file, so the first sync leaves a backup behind.
    fs.writeFileSync(sync.agentsPath, 'Stale generated text.\n');
    const { results, sizes, output } = syncFourTimes(sync);
    assert.match(output, /Keep this rule\./);
    assert.doesNotMatch(output, /Stale generated text\./);
    assert.equal((output.match(/Generated by the mynameisjev/g) || []).length, 1);
    assert.deepEqual(results, ['updated', 'unchanged', 'unchanged', 'unchanged']);
    assert.deepEqual(sizes, [sizes[0], sizes[0], sizes[0], sizes[0]]);
  });
}

test('sync does not read AGENTS.md back in through a link outside the Codex directory', (t) => {
  const { root, sync } = setup(t);
  try {
    fs.symlinkSync(sync.agentsPath, path.join(root, 'dotfiles', 'shared.md'));
  } catch (e) {
    if (e.code === 'EPERM') return t.skip('symlinks need extra rights here');
    throw e;
  }
  fs.writeFileSync(path.join(process.env.CLAUDE_CONFIG_DIR, 'CLAUDE.md'), '# CLAUDE.md\n\nKeep this rule.\n\n@~/dotfiles/shared.md\n');
  const { results, sizes, output } = syncFourTimes(sync);
  assert.equal((output.match(/Generated by the mynameisjev/g) || []).length, 1);
  assert.deepEqual(results, ['updated', 'unchanged', 'unchanged', 'unchanged']);
  assert.deepEqual(sizes, [sizes[0], sizes[0], sizes[0], sizes[0]]);
});

test('sync includes AGENTS.local.md once when an import name matches it except for case', (t) => {
  const { root, sync, folds } = setup(t);
  fs.writeFileSync(path.join(root, 'dotfiles', 'agents.local.md'), 'Shared local rule.\n');
  fs.writeFileSync(path.join(process.env.CLAUDE_CONFIG_DIR, 'CLAUDE.md'), '# CLAUDE.md\n\n@~/dotfiles/agents.local.md\n');
  fs.writeFileSync(path.join(process.env.CODEX_HOME, 'AGENTS.local.md'), 'Codex only rule.\n');
  if (!folds) fs.symlinkSync('AGENTS.local.md', path.join(process.env.CODEX_HOME, 'agents.local.md'));
  const { results, output } = syncFourTimes(sync);
  assert.equal((output.match(/Codex only rule\./g) || []).length, 1);
  assert.match(output, /Shared local rule\./);
  assert.deepEqual(results, ['updated', 'unchanged', 'unchanged', 'unchanged']);
});

function link(t, target, file) {
  try {
    fs.symlinkSync(target, file);
    return true;
  } catch (e) {
    if (e.code !== 'EPERM') throw e;
    t.skip('symlinks need extra rights here');
    return false;
  }
}

for (const how of ['directly', 'through a link']) {
  test(`sync appends AGENTS.local.md once when CLAUDE.md imports it ${how}`, (t) => {
    const { root, sync } = setup(t);
    const local = path.join(process.env.CODEX_HOME, 'AGENTS.local.md');
    fs.writeFileSync(local, 'Codex only rule.\n');
    let ref = '~/.codex/AGENTS.local.md';
    if (how !== 'directly') {
      if (!link(t, local, path.join(root, 'dotfiles', 'mine.md'))) return;
      ref = '~/dotfiles/mine.md';
    }
    fs.writeFileSync(path.join(process.env.CLAUDE_CONFIG_DIR, 'CLAUDE.md'), `# CLAUDE.md\n\nBefore.\n\n@${ref}\n\nAfter.\n`);
    const { results, output } = syncFourTimes(sync);
    assert.equal((output.match(/Codex only rule\./g) || []).length, 1);
    assert.ok(output.indexOf('Codex only rule.') > output.indexOf('After.'), 'local block stays in its appended place');
    assert.match(output, /<!-- jev-include: AGENTS\.local\.md -->\nCodex only rule\.\n<!-- jev-include-end -->/);
    assert.doesNotMatch(output, /not found/);
    assert.deepEqual(results, ['updated', 'unchanged', 'unchanged', 'unchanged']);
  });
}

for (const name of ['AGENTS.md', 'AGENTS.md.jev.bak']) {
  test(`sync does not append ${name} when AGENTS.local.md is a link to it`, (t) => {
    const { sync } = setup(t);
    fs.writeFileSync(sync.agentsPath, 'Stale generated text.\n');
    fs.writeFileSync(sync.backupPath, 'Older generated text.\n');
    if (!link(t, name, path.join(process.env.CODEX_HOME, 'AGENTS.local.md'))) return;
    const { results, sizes, output } = syncFourTimes(sync);
    assert.match(output, /Shared rule: run tests\./);
    assert.doesNotMatch(output, /generated text\./);
    assert.equal((output.match(/Generated by the mynameisjev/g) || []).length, 1);
    assert.deepEqual(results, ['updated', 'unchanged', 'unchanged', 'unchanged']);
    assert.deepEqual(sizes, [sizes[0], sizes[0], sizes[0], sizes[0]]);
  });
}

for (const name of ['AGENTS.md', 'AGENTS.md.jev.bak']) {
  test(`sync skips with a reason when CLAUDE.md is a link to ${name}`, async (t) => {
    const { sync } = setup(t);
    fs.writeFileSync(sync.agentsPath, 'Generated text.\n');
    fs.writeFileSync(sync.backupPath, 'Older generated text.\n');
    const claudeMd = path.join(process.env.CLAUDE_CONFIG_DIR, 'CLAUDE.md');
    fs.rmSync(claudeMd);
    if (!link(t, path.join(process.env.CODEX_HOME, name), claudeMd)) return;
    const reason = 'skipped: CLAUDE.md is the generated AGENTS.md or its backup';
    assert.deepEqual([sync.syncAgents({}), sync.syncAgents({})], [reason, reason]);
    assert.equal(fs.readFileSync(sync.agentsPath, 'utf8'), 'Generated text.\n');
    assert.equal(fs.readFileSync(sync.backupPath, 'utf8'), 'Older generated text.\n');
    assert.equal(sync.agentsStatus({}), 'claude-md-is-generated');
    assert.equal(sync.buildAgents({}), null);
    const lines = await sync.ensureAll({});
    assert.ok(lines.includes(`Codex AGENTS.md: ${reason}`), lines.join('\n'));
  });
}

test('sync does not claim to append a blank AGENTS.local.md that CLAUDE.md imports', (t) => {
  const { sync } = setup(t);
  fs.writeFileSync(path.join(process.env.CODEX_HOME, 'AGENTS.local.md'), ' \n');
  fs.writeFileSync(path.join(process.env.CLAUDE_CONFIG_DIR, 'CLAUDE.md'), '# CLAUDE.md\n\n@~/.codex/AGENTS.local.md\n');
  const { results, output } = syncFourTimes(sync);
  assert.doesNotMatch(output, /appended below/);
  assert.match(output, /<!-- jev-include: ~\/\.codex\/AGENTS\.local\.md is AGENTS\.local\.md, which is empty -->/);
  assert.doesNotMatch(output, /<!-- jev-include: AGENTS\.local\.md -->/);
  assert.deepEqual(results, ['updated', 'unchanged', 'unchanged', 'unchanged']);
});
