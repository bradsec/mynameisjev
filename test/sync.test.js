const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'jev-sync-'));
const claudeDir = path.join(tmp, 'claude');
const codexHome = path.join(tmp, 'codex');
process.env.CLAUDE_CONFIG_DIR = claudeDir;
process.env.CODEX_HOME = codexHome;
fs.mkdirSync(path.join(claudeDir, 'plugins'), { recursive: true });
fs.writeFileSync(path.join(claudeDir, 'plugins', 'installed_plugins.json'), '{"plugins":{}}');
fs.writeFileSync(path.join(claudeDir, 'CLAUDE.md'), [
  '# CLAUDE.md',
  '',
  '## Rules',
  '- shared rule',
  '<!-- claude-only:start -->',
  '- claude only rule',
  '<!-- claude-only:end -->',
  '',
  '@RTK.md',
].join('\n'));
fs.writeFileSync(path.join(claudeDir, 'RTK.md'), 'claude rtk body\n');

const sync = require('../plugin/scripts/jev-sync');

test('skips generation when Codex is not installed', () => {
  assert.strictEqual(sync.agentsStatus({ style: null }), 'no-codex');
  assert.match(sync.syncAgents({ style: null }), /skipped/);
});

test('project instruction check follows Codex file precedence and fallback config', () => {
  const project = path.join(tmp, 'project');
  fs.mkdirSync(project, { recursive: true });
  const config = path.join(codexHome, 'config.toml');
  fs.mkdirSync(codexHome, { recursive: true });
  const check = () => sync.projectInstructions(project);
  assert.strictEqual(check().line, 'Codex sees no project instructions here');
  fs.writeFileSync(path.join(project, 'CLAUDE.md'), '# Rules\n');
  assert.deepStrictEqual(check().lines.slice(0, 2), [
    'Codex sees no project instructions here',
    'Add to ~/.codex/config.toml: project_doc_fallback_filenames = ["CLAUDE.md"]',
  ]);
  fs.writeFileSync(config, '[other]\nproject_doc_fallback_filenames = ["CLAUDE.md"]\n');
  assert.strictEqual(check().line, 'Codex sees no project instructions here');
  fs.writeFileSync(config, 'project_doc_fallback_filenames = ["OTHER.md", "CLAUDE.md"]\n');
  assert.strictEqual(check().line, 'Codex reads CLAUDE.md here (fallback)');
  fs.writeFileSync(config, 'project_doc_fallback_filenames = [\n  "bracket].md",\n  "CLAUDE.md", # included\n]\n');
  assert.strictEqual(check().line, 'Codex reads CLAUDE.md here (fallback)');
  fs.writeFileSync(path.join(project, 'AGENTS.md'), '# Agents\n');
  assert.strictEqual(check().line, 'Codex reads AGENTS.md here');
  fs.writeFileSync(path.join(project, 'AGENTS.override.md'), '# Override\n');
  assert.strictEqual(check().line, 'Codex reads AGENTS.md here');
});

test('project instruction check reports unknown config and raw Claude warnings', () => {
  const project = path.join(tmp, 'warnings');
  fs.mkdirSync(project, { recursive: true });
  fs.writeFileSync(path.join(project, 'CLAUDE.md'), '@rules.md\n<!-- claude-only:start -->\n' + 'x'.repeat(32768));
  fs.writeFileSync(path.join(codexHome, 'config.toml'), 'project_doc_fallback_filenames = [not-valid]\n');
  const lines = sync.projectInstructions(project).lines;
  assert.match(lines[0], /unknown/);
  assert.ok(lines.some((line) => /@file imports/.test(line)));
  assert.ok(lines.some((line) => /32 KiB/.test(line)));
  assert.ok(lines.some((line) => /claude-only/.test(line)));
});

test('generated AGENTS.md: title swapped, claude-only removed, imports inlined', () => {
  fs.mkdirSync(codexHome, { recursive: true });
  const text = sync.buildAgents({ style: null });
  assert.match(text, /^<!-- Generated by the mynameisjev plugin/);
  assert.match(text, /\n# AGENTS\.md\n\n## Rules/);
  assert.doesNotMatch(text, /claude only rule/);
  assert.match(text, /Prefix every shell command with `rtk`/, 'Claude RTK rules get the prefix rule for Codex');
  assert.match(text, /claude rtk body/);
  assert.match(text, /sandbox, permission, or network denial/);
});

test('a Codex variant of an import wins, and AGENTS.local.md is appended', () => {
  fs.writeFileSync(path.join(codexHome, 'RTK.md'), 'codex rtk body\n');
  fs.writeFileSync(path.join(codexHome, 'AGENTS.local.md'), 'codex only rule\n');
  const text = sync.buildAgents({ style: null });
  assert.match(text, /codex rtk body/);
  assert.doesNotMatch(text, /claude rtk body/);
  assert.match(text, /codex only rule/);
});

test('style block included only when a style skill is given', () => {
  const style = { id: 'voice:brief', body: '# Brief\nKeep facts.' };
  assert.match(sync.buildAgents({ style }), /jev-style:start[\s\S]*# Brief[\s\S]*jev-style:end/);
  assert.doesNotMatch(sync.buildAgents(), /jev-style/);
});

test('sync writes once, keeps a backup of the replaced file', () => {
  fs.writeFileSync(path.join(codexHome, 'AGENTS.md'), 'hand written\n');
  assert.strictEqual(sync.syncAgents({ style: null }), 'updated');
  assert.strictEqual(sync.syncAgents({ style: null }), 'unchanged');
  assert.strictEqual(fs.readFileSync(sync.backupPath, 'utf8'), 'hand written\n');
  assert.strictEqual(sync.agentsStatus({ style: null }), 'in-sync');
});

test('ensureAll reports discovered plugins and style without installing plugins', async (t) => {
  const plugins = require('../plugin/scripts/jev-plugins');
  const exec = require('../plugin/scripts/jev-exec');
  t.mock.method(exec, 'findOnPath', () => null);
  t.mock.method(exec, 'run', () => assert.fail('No plugin or RTK installation should run'));
  t.mock.method(plugins, 'pluginPairs', async () => [{
    name: 'tools', claude: { id: 'tools@local', version: '1.0' },
    codex: { id: 'tools@remote', status: 'missing', version: null },
  }]);
  const style = { id: 'voice:brief', body: 'Keep facts.' };
  const lines = await sync.ensureAll({ style });
  assert.ok(lines.includes('Output style for Codex: voice:brief'));
  assert.ok(lines.some((line) => line.includes('codex plugin add tools@remote')));
  assert.match(fs.readFileSync(sync.agentsPath, 'utf8'), /jev-style:start/);
  const off = await sync.ensureAll({ style: null, reason: 'none found' });
  assert.ok(off.includes('Output style for Codex: none (none found)'));
  assert.doesNotMatch(fs.readFileSync(sync.agentsPath, 'utf8'), /jev-style:start/);
});

test('ensureAll reports discovery errors and still generates instructions', async (t) => {
  t.mock.method(require('../plugin/scripts/jev-exec'), 'findOnPath', () => null);
  t.mock.method(require('../plugin/scripts/jev-plugins'), 'pluginPairs', async () => { throw new Error('cannot list'); });
  const lines = await sync.ensureAll();
  assert.ok(lines.includes('Plugin discovery: cannot list'));
  assert.ok(lines.includes('Codex AGENTS.md: unchanged'));
});
